export function milliseconds(value) {
  if (value === null || value === undefined || value === "" || value === 0)
    return NaN;
  if (typeof value === "number") return value < 1e12 ? value * 1000 : value;
  return new Date(value).getTime();
}
export function relativeDate(value, now = Date.now()) {
  const time = milliseconds(value);
  if (!Number.isFinite(time)) return "";
  const minutes = Math.max(0, Math.floor((now - time) / 60000));
  if (minutes < 1) return "刚刚";
  if (minutes < 60) return `${minutes}分钟前`;
  if (minutes < 1440) return `${Math.floor(minutes / 60)}小时前`;
  const date = new Date(time);
  const today = new Date(now);
  const days = Math.round(
    (new Date(today.getFullYear(), today.getMonth(), today.getDate()) -
      new Date(date.getFullYear(), date.getMonth(), date.getDate())) /
      86400000,
  );
  if (days < 7) return `${days}天前`;
  return `${date.getFullYear() !== new Date(now).getFullYear() ? date.getFullYear() + "年" : ""}${date.getMonth() + 1}月${date.getDate()}日`;
}
export function fullDate(value) {
  const time = milliseconds(value);
  return Number.isFinite(time)
    ? new Date(time).toLocaleString("zh-CN", { hour12: false })
    : "";
}
export function runDate(value, now = Date.now()) {
  const time = milliseconds(value);
  if (!Number.isFinite(time)) return "时间未提供";
  const date = new Date(time),
    today = new Date(now);
  const day = new Date(
    date.getFullYear(),
    date.getMonth(),
    date.getDate(),
  ).getTime();
  const start = new Date(
    today.getFullYear(),
    today.getMonth(),
    today.getDate(),
  ).getTime();
  const label =
    day === start
      ? "今天 "
      : day === start - 86400000
        ? "昨天 "
        : day === start + 86400000
          ? "明天 "
          : "";
  return `${label}${date.getMonth() + 1}月${date.getDate()}日 ${date.toLocaleTimeString("zh-CN", { hour: "2-digit", minute: "2-digit", hour12: false })}`;
}
export function scheduleLabel(definition) {
  const schedule = definition?.schedule;
  if (schedule?.type === "once") return runDate(schedule.scheduledAt);
  const rule = Object.fromEntries(
    (schedule?.rrule ?? "")
      .split(";")
      .filter((x) => x.includes("="))
      .map((x) => x.split("=")),
  );
  if (!rule.BYHOUR || !rule.BYMINUTE) return "";
  const clock = `${rule.BYHOUR.padStart(2, "0")}:${rule.BYMINUTE.padStart(2, "0")}`;
  if (rule.FREQ === "DAILY" && !rule.BYDAY) return `每天 ${clock}`;
  const days = {
    MO: "一",
    TU: "二",
    WE: "三",
    TH: "四",
    FR: "五",
    SA: "六",
    SU: "日",
  };
  if (rule.BYDAY === "MO,TU,WE,TH,FR") return `工作日 ${clock}`;
  if (rule.BYDAY)
    return `每周${rule.BYDAY.split(",")
      .map((x) => days[x] ?? x)
      .join("、")} ${clock}`;
  return clock;
}
const activity = (item) =>
  milliseconds(item.lastActivityAt ?? item.updatedAt ?? item.createdAt) || 0;
export function projectTasks(sessions, definitions = []) {
  const definitionsByID = new Map(definitions.map((d) => [d.id, d]));
  const groups = new Map(),
    result = [];
  for (const item of sessions) {
    if (
      item.lifecycle === "archived" ||
      item.transport === "cloud" ||
      item.kind === "assistant" ||
      item.space?.type === "assistant" ||
      item.projectId
    )
      continue;
    const id = item.isBackgroundAutomation && item.tags?.automationId;
    if (id && definitionsByID.has(id)) {
      const group = groups.get(id) ?? [];
      group.push(item);
      groups.set(id, group);
    } else
      result.push({ ...item, inTaskList: item.space?.autoGenerated !== false });
  }
  for (const [id, definition] of definitionsByID) {
    const runs = (groups.get(id) ?? []).sort(
      (a, b) => activity(b) - activity(a),
    );
    const latest = runs[0];
    result.push({
      ...latest,
      id: `automation:${id}`,
      automationId: id,
      definition,
      isAutomationAggregate: true,
      title: definition.name || latest?.title || "定时任务",
      lastActivityAt: latest?.lastActivityAt ?? definition.createdAt,
      unread: runs.some((x) => x.unread),
      isPinned: false,
      space: {
        type: "local",
        cwd: definition.execution?.cwd ?? latest?.space?.cwd,
      },
      inTaskList: definition.execution?.workspaceScope !== "workspace",
    });
  }
  return result.sort(
    (a, b) =>
      Number(!!b.isPinned) - Number(!!a.isPinned) ||
      activity(b) - activity(a) ||
      a.id.localeCompare(b.id),
  );
}
