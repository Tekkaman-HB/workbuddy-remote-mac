export function taskRows(items) {
  return items
    .map(
      (item) =>
        `<div class="task-row ${(state.automation?.id ?? state.session?.id) === item.id ? "active" : ""}" data-session="${esc(item.id)}" tabindex="0" role="button" aria-label="${esc(item.title || "新任务")}"><span class="task-title">${esc(item.title || "新任务")}</span>${isRunning(item.state) ? '<i class="running-dot" aria-label="进行中"></i>' : item.unread ? '<i class="unread-dot" aria-label="未读"></i>' : `<time title="${esc(fullDate(item.lastActivityAt ?? item.updatedAt))}">${relativeDate(item.lastActivityAt ?? item.updatedAt)}</time>`}${item.isAutomationAggregate ? "" : `<button class="task-menu" data-task-menu="${esc(item.id)}" aria-label="任务菜单">${icon("more")}</button>`}</div>`,
    )
    .join("");
}
export function renderSidebar() {
  const catalogName = Object.entries({
    experts: "专家",
    skills: "技能",
    connectors: "连接器",
  })
    .filter(([key]) => state.features[key])
    .map(([, name]) => name)
    .join("·");
  const nav = [
    ["new", "新建任务", "new"],
    ["catalog", catalogName, "owl"],
    ["automations", "定时任务", "clock"],
  ];
  $("#navigation").innerHTML = nav
    .filter(
      ([action]) =>
        action === "new" ||
        (action === "catalog"
          ? ["experts", "skills", "connectors"].some((key) => state.features[key])
          : state.features.automations),
    )
    .map(
      ([action, name, i]) =>
        `<button data-action="${action}" class="${action === "new" && state.view === "home" ? "active" : ""}">${icon(i)}${name}</button>`,
    )
    .join("");
  const all = visibleSessions();
  const pinned = all.filter((x) => x.isPinned);
  const others = all.filter((x) => !x.isPinned);
  $("#tasks").innerHTML =
    (pinned.length ? `<div class="section-heading">置顶 (${pinned.length})</div>${taskRows(pinned)}` : "") +
    `<div class="section-heading">任务 (${others.length})${state.loading ? '<span class="spinner" role="status" aria-label="加载中"></span>' : ""}</div>` +
    taskRows(others) +
    (!all.length ? `<div class="empty">${state.connected ? "暂无任务" : "连接远端 Mac 后<br>查看本地任务"}</div>` : "");
  const workspacePaths = new Set(state.sessions.filter(s => s.space?.type === "local" && s.space.autoGenerated === false && s.lifecycle !== "archived").map(s => s.space.cwd));
  const spaces = state.workspaces.map((w, i) => ({w, i})).filter(({w}) => workspacePaths.has(workspacePath(w)));
  $("#spaces").innerHTML =
    `<div class="section-heading">空间 (${spaces.length})</div>` +
    spaces
      .map(({w, i}) => `<button class="space-row" data-workspace-view="${i}" title="${esc(workspacePath(w))}">${icon("folder")}<span>${esc(workspaceName(w))}</span></button>`)
      .join("");
  $("#profile-name").textContent = accountName();
  const name = $("#profile-name").textContent;
  const avatar = state.authStatus === "signedIn" ? state.profile.avatarUrl ?? state.profile.avatar : null;
  $(".avatar").innerHTML =
    typeof avatar === "string" && /^https:\/\//.test(avatar)
      ? `<img src="${esc(avatar)}" alt="">`
      : esc(state.authStatus === "signedIn" ? name.slice(0, 1) : "W");
  document.body.classList.toggle("connected", state.connected);
  $("#device-button").title = state.device
    ? `${state.device.displayName} · ${state.connected ? "已连接" : "未连接"}`
    : "连接远端 Mac";
}
export function updateTitle() {
  $("#conversation-title").textContent = state.view === "home" ? "" : state.automation?.title ?? state.session?.title ?? "新任务";
  $("#conversation-schedule").textContent = state.automation ? scheduleLabel(state.automation.definition) : "";
}
let previousView;
export function renderPage() {
  const home = state.view === "home";
  $("#home").hidden = !home;
  $("#chat").hidden = home;
  updateTitle();
  document.body.classList.toggle("automation-view", !!state.automation);
  $("#composer-wrap").hidden = !!state.automation;
  $(".title-actions")
    .querySelectorAll("button")
    .forEach((b, i) => {
      b.hidden = home || !!state.automation || (i === 2 && !state.features.files);
    });
  (home ? $("#home-composer-slot") : $("#chat-composer-slot")).append($("#composer-wrap"));
  $("#prompt").placeholder = home ? "向远端 Mac 发送任务…" : "继续向远端 WorkBuddy 发送消息";
  if (previousView !== state.view) enter(home ? $("#home") : $("#chat"), { distance: 5, duration: state.automation ? 0 : 220 });
  previousView = state.view;
  updateComposer();
  renderSidebar();
}
export function updateComposer() {
  $("#model-button").hidden = !state.features.models;
  $("#workspace-button").hidden = !state.features.workspaces;
  $("#spaces").hidden = !state.features.workspaces;
  const fileButton = document.querySelector('[data-action="files"]');
  fileButton.hidden = state.view === "home" || !!state.automation || !state.features.files;
  const selected = state.models.find((m) => modelId(m) === state.config.model);
  $("#model-button").innerHTML =
    '<span class="control-label">' +
    esc((selected ? modelName(selected) + (selected.custom ? " · 自定义" : "") : state.config.model) || "选择模型") +
    "</span>" +
    icon("chevronDown", "dropdown-chevron");
  $("#model-button").title = selected ? `${modelName(selected)} · ${modelId(selected)}` : "选择模型";
  const full = state.config.permissionMode === "fullAccess";
  document.querySelectorAll(".permission").forEach((el) => {
    el.innerHTML =
      icon("shield") +
      '<span class="control-label">' +
      (full ? "允许完全访问" : "默认权限") +
      "</span>" +
      icon("chevronDown", "dropdown-chevron");
  });
  $("#workspace-button").innerHTML =
    icon("folder") +
    `<span class="control-label">${esc(workspaceName(state.workspace ?? state.session?.space))}</span>` +
    icon("chevronDown", "dropdown-chevron");
  $("#workspace-button").title = workspacePath(state.workspace ?? state.session?.space) || "选择工作空间";
  const expert = state.config.expertId;
  $("#composer-tags").innerHTML =
    expert && state.features.experts
      ? `<button class="context-chip" data-action="expert">${icon("owl")}${esc(catalogName(state.catalogs.experts?.find((x) => (x.id ?? x.expertId) === expert) ?? {id: expert}))}</button>`
      : "";
  const running = state.sending || isRunning(state.session?.state) || isRunning(state.records.at(-1)?.state);
  $("#send-button").hidden = running;
  $("#stop-button").hidden = !running;
  $("#send-button").disabled = !state.connected || !$("#prompt").value.trim() || state.loading;
  $("#stop-button").disabled = !state.session;
}
const messageNodes = new Map();
export function resetHistory() {
  messageNodes.clear();
  delete $("#messages").dataset.automationSignature;
  $("#messages").replaceChildren();
}
function requestHTML(record) {
  return `${record.userMessage ? `<div class="user-message"><div class="user-bubble">${blocks(record.userMessage)}</div></div>` : ""}
    <div class="assistant-label"><span class="buddy-icon">${icon("buddy")}</span>WorkBuddy ${isRunning(record.state) ? '<span class="spinner" role="status" aria-label="加载中"></span>' : ""}</div>
    <div class="assistant-message">${record.assistantMessage ? assistantReply(record) : `<div class="reply-status">${isRunning(record.state) ? '<span class="spinner" role="status" aria-label="加载中"></span>正在处理…' : "暂无回复内容"}</div>`}</div>${messageActions(record)}`;
}
export function renderMessages(forceBottom = false) {
  if (state.automation) { automationMessages(forceBottom); return; }
  const root = $("#messages");
  const position = captureHistoryPosition();
  const edge = renderHistoryEdge();
  root
    .querySelectorAll(":scope > .empty,:scope > .reply-status,:scope > .loading-skeleton")
    .forEach((el) => el.remove());
  if (!state.records.length) {
    root.insertAdjacentHTML(
      "beforeend",
      state.loading
        ? '<div class="reply-status"><span class="spinner" role="status" aria-label="加载中"></span>正在读取远端会话…</div><div class="loading-skeleton"></div><div class="loading-skeleton"></div>'
        : '<div class="empty">任务已就绪，发送消息开始对话</div>',
    );
  }
  const active = new Set();
  let previous = edge;
  for (const record of state.records) {
    active.add(record.id);
    const signature = JSON.stringify([
      record.userMessage,
      record.assistantMessage,
      record.state,
      record.responseModel,
      record.timestamp,
      record.finishTimestamp,
      record.completedAt,
    ]);
    let entry = messageNodes.get(record.id);
    if (!entry) {
      const node = document.createElement("article");
      node.className = "request";
      node.dataset.request = record.id;
      if (messageNodes.size && record === state.records.at(-1)) enter(node, { distance: 4, duration: 180 });
      entry = { node, signature: null };
      messageNodes.set(record.id, entry);
    }
    if (entry.signature !== signature) {
      const detailKey = (d, i) => d.dataset.detailKey ?? `html:${i}`;
      const expanded = new Map([...entry.node.querySelectorAll("details")].map((d, i) => [detailKey(d, i), d.open]));
      entry.node.innerHTML = requestHTML(record);
      entry.node.querySelectorAll("details").forEach((d, i) => {
        if (expanded.has(detailKey(d, i))) d.open = expanded.get(detailKey(d, i));
      });
      entry.signature = signature;
    }
    const expected = previous ? previous.nextSibling : root.firstChild;
    if (expected !== entry.node) root.insertBefore(entry.node, expected);
    previous = entry.node;
  }
  for (const [id, entry] of messageNodes) {
    if (!active.has(id)) {
      entry.node.remove();
      messageNodes.delete(id);
    }
  }
  restoreHistoryPosition(position, forceBottom);
  updateComposer();
}
export function toast(text) {
  const el = $("#toast");
  el.textContent = text;
  reveal(el, { kind: "toast" });
  clearTimeout(toast.timer);
  toast.timer = setTimeout(() => {
    dismiss(el, { kind: "toast" });
  }, 6000);
}
export function banner(text) {
  $("#connection-banner").textContent = text;
  $("#connection-banner").hidden = !text;
}
