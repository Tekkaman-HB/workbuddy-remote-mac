import test from "node:test";
import assert from "node:assert/strict";
import { state, visibleSessions, relativeDate } from "../ui/state.js";
import { conversationRevision, applyReadReceipts, projectTasks } from "../ui/tasks.js";

test("定时任务按身份聚合执行记录，同名普通会话保持独立", () => {
  Object.assign(state, {
    search: "",
    filter: "all",
    features: { automations: true },
    catalogs: {
      automations: [{ id: "daily", name: "每日复盘", createdAt: 1000 }],
    },
    sessions: [
      {
        id: "run-new",
        title: "每日复盘",
        transport: "local",
        isBackgroundAutomation: true,
        tags: { automationId: "daily" },
        lastActivityAt: 4000,
      },
      {
        id: "run-old",
        title: "每日复盘",
        transport: "local",
        isBackgroundAutomation: true,
        tags: { automationId: "daily" },
        lastActivityAt: 3000,
        unread: true,
      },
      { id: "manual-a", title: "每日复盘", lastActivityAt: 2000 },
      { id: "manual-b", title: "每日复盘", lastActivityAt: 1000 },
    ],
  });
  const rows = visibleSessions();
  assert.equal(rows.length, 3);
  assert.equal(rows[0].id, "automation:daily");
  assert.equal(rows[0].unread, true);
  assert.deepEqual(
    rows.slice(1).map((x) => x.id),
    ["manual-a", "manual-b"],
  );
});

test("当日任务以真实分钟和小时显示，旧任务显示月日", () => {
  const now = Date.now;
  Date.now = () => new Date("2026-11-14T08:00:00+08:00").getTime();
  try {
    assert.equal(relativeDate(Date.now() - 23 * 3600000), "23小时前");
    assert.equal(relativeDate(Date.now() - 38 * 60000), "38分钟前");
    assert.equal(relativeDate(Date.now() - 4 * 86400000), "4天前");
    assert.equal(
      relativeDate(new Date("2026-11-10T21:00:00+08:00").getTime()),
      "4天前",
    );
    assert.equal(
      relativeDate(new Date("2026-11-06T08:00:00+08:00").getTime()),
      "11月6日",
    );
  } finally {
    Date.now = now;
  }
});

test("归档、助理和独立空间不混入任务区，空间里的自动化仍可从空间打开", () => {
  const rows = projectTasks(
    [
      { id: "archived", lifecycle: "archived" },
      { id: "assistant", kind: "assistant" },
      {
        id: "workspace",
        space: { type: "local", autoGenerated: false, cwd: "/test/work" },
      },
      { id: "task", space: { type: "local", autoGenerated: true } },
    ],
    [
      {
        id: "schedule",
        name: "空间任务",
        execution: { workspaceScope: "workspace", cwd: "/test/work" },
      },
    ],
  );
  assert.deepEqual(
    rows.filter((x) => x.inTaskList).map((x) => x.id),
    ["task"],
  );
  assert.equal(
    rows.find((x) => x.id === "automation:schedule").space.cwd,
    "/test/work",
  );
  assert.equal(rows.length, 3);
});

test("已读回执挡住旧未读回包，新活动恢复绿点且不修改输入", () => {
  const item={id:'chat', unread:true, lastActivityAt:1000, updatedAt:1000, state:'completed'};
  const receipts=new Map([['chat',conversationRevision(item)]]);
  assert.equal(applyReadReceipts([item],receipts)[0].unread,false);
  assert.equal(item.unread,true);
  assert.equal(applyReadReceipts([{...item,lastActivityAt:2000}],receipts)[0].unread,true);
  assert.equal(applyReadReceipts([{...item,id:'other'}],receipts)[0].unread,true);
});
